# -----------------------------
# -- Arithmetic Operations --
# -----------------------------

a = 10
b = 3

print (a + b)     # ==> addition
print (a - b)     # ==> subtraction
print (a * b)     # ==> multiplication
print (a / b)     # ==> division
print (a % b)     # ==> modulus "rest of division"
print (a ** b)    # ==> exponent
print (a // b)    # ==> floor division